document.addEventListener('DOMContentLoaded', () => {
    // 1. Create/Inject Language Switcher
    const themeToggle = document.getElementById('theme-toggle');
    const rightSideContainer = themeToggle ? themeToggle.parentNode : null;

    if (rightSideContainer) {
        // Create switcher container
        const langContainer = document.createElement('div');
        langContainer.className = "relative group";

        // Button - Matching theme-toggle styles exactly
        langContainer.innerHTML = `
            <button id="lang-btn" class="inline-flex items-center justify-center whitespace-nowrap rounded-md text-sm font-medium ring-offset-background transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 disabled:pointer-events-none disabled:opacity-50 hover:bg-accent hover:text-accent-foreground h-9 w-9">
                <i data-lucide="globe" class="h-[1.2rem] w-[1.2rem]"></i>
                <span class="sr-only">Alterar idioma</span>
            </button>
            <div class="absolute right-0 top-full mt-2 w-32 rounded-md border border-border bg-white/85 backdrop-blur-md dark:bg-[#1E1E2A]/90 p-1 shadow-md opacity-0 invisible group-hover:opacity-100 group-hover:visible transition-all duration-200 z-50">
                <button class="lang-option w-full rounded-sm px-2 py-1.5 text-left text-sm hover:bg-accent hover:text-accent-foreground transition-colors flex items-center gap-2" data-lang="pt">
                    <span>🇧🇷</span> Português
                </button>
                <button class="lang-option w-full rounded-sm px-2 py-1.5 text-left text-sm hover:bg-accent hover:text-accent-foreground transition-colors flex items-center gap-2" data-lang="en">
                    <span>🇺🇸</span> English
                </button>
                <button class="lang-option w-full rounded-sm px-2 py-1.5 text-left text-sm hover:bg-accent hover:text-accent-foreground transition-colors flex items-center gap-2" data-lang="es">
                    <span>🇪🇸</span> Español
                </button>
            </div>
        `;

        // Insert after Theme Toggle (to the right of it)
        rightSideContainer.insertBefore(langContainer, themeToggle.nextSibling);

        if (typeof lucide !== 'undefined') lucide.createIcons();
    }

    // 2. Language Logic
    const savedLang = localStorage.getItem('site_lang') || 'pt';
    setLanguage(savedLang);

    // Event Listeners
    document.querySelectorAll('.lang-option').forEach(btn => {
        btn.addEventListener('click', (e) => {
            const lang = e.currentTarget.getAttribute('data-lang');
            setLanguage(lang);
        });
    });

    function setLanguage(lang) {
        // Save preference
        localStorage.setItem('site_lang', lang);

        // Update Button Label
        const label = document.getElementById('current-lang-label');
        if (label) label.textContent = lang.toUpperCase();

        // Update DOM elements
        const elements = document.querySelectorAll('[data-i18n]');
        elements.forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                // Check if element is an input with placeholder
                if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                    el.placeholder = translations[lang][key];
                } else {
                    el.innerHTML = translations[lang][key]; // Using innerHTML to allow simple HTML like <b>
                }
            }
        });

        // Special handling for dynamic content if needed
        // e.g. updating document title
    }

    // Expose globally for mobile nav language buttons
    window.changeLanguage = setLanguage;
});
